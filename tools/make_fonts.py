"""Generate small, antialiased VLW font subsets from the bundled OFL Manrope."""
from pathlib import Path
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def build(name, size, characters):
    font = ImageFont.truetype(str(ROOT / "assets/fonts/Manrope.ttf"), size)
    try:
        font.set_variation_by_axes([600])
    except (OSError, ValueError):
        pass
    glyphs, bitmaps = [], []
    ascent = descent = 0
    for char in sorted(set(characters)):
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right-left, bottom-top
        advance = round(font.getlength(char))
        ascent, descent = max(ascent, -top), max(descent, bottom)
        glyphs.append(struct.pack(">7i", ord(char), height, width, advance, -top, left, 0))
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
            bitmaps.append(image.tobytes())
    data = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    data += b"".join(glyphs) + b"".join(bitmaps)
    rows = [", ".join(f"0x{byte:02x}" for byte in data[i:i+20]) for i in range(0,len(data),20)]
    return f"const uint8_t {name}[] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n"


chars = "".join(chr(i) for i in range(32,127)) + "áéíóúñüÁÉÍÓÚÑÜ¿¡·"
header = "// Generated by tools/make_fonts.py from Manrope (SIL OFL 1.1).\n#pragma once\n#include <Arduino.h>\n"
header += build("FontBody", 15, chars)
header += build("FontTitle", 22, chars)
header += build("FontClock", 72, "0123456789:")
(ROOT / "include/Fonts.h").write_text(header, encoding="ascii")
print("Generated include/Fonts.h")
